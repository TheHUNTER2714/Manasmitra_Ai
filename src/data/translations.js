/**
 * Helper to retrieve localized text with graceful fallbacks
 * @param {string} key - Dictionary key
 * @param {string} lang - Language code (hi, en, as, bn, brx, kha, grt, mni, lus, naga, trp)
 * @param {string} fallback - Optional default fallback string
 * @returns {string} Localized string
 */
export function getLocalizedText(key, lang = 'hi', fallback = '') {
  if (UI_TRANSLATIONS[key]) {
    const entry = UI_TRANSLATIONS[key];
    if (entry[lang]) return entry[lang];
    if (entry['en']) return entry['en'];
    if (entry['hi']) return entry['hi'];
  }
  return fallback || key;
}

/**
 * Short alias for getLocalizedText
 */
export const t = getLocalizedText;
