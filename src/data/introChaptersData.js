/**
 * Resolves localized strings for any chapter in any of the 11 supported languages
 */
export function getChapterLocalized(chapter, lang = 'hi') {
  if (!chapter) return null;
  const trans = chapter.translations;
  if (trans && trans[lang]) {
    return trans[lang];
  }
  if (trans && trans['en']) {
    return trans['en'];
  }
  if (trans && trans['hi']) {
    return trans['hi'];
  }
  return {
    title: chapter.id,
    badge: 'Overview',
    narration: '',
    actionText: 'Open'
  };
}

